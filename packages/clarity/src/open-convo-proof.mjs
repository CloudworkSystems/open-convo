function renderBullets(items) {
  return items.map((item) => `- ${item}`).join("\n");
}

function renderRecords(records, fields) {
  return records
    .map((record) => fields.map(([label, key]) => `  ${label}: ${record[key]}`).join("\n"))
    .join("\n\n");
}

