/**
 * Atlas index engine. Notes go in, and generated indexes, a root map, and a
 * health list come out. This file reads and writes nothing. The same notes
 * always produce the same result.
 */

export const GENERATED_HEADER = '<!-- Generated by atlas-index. Do not edit by hand. -->';
export const MAP_MARKER = '<!-- atlas-index:start -->';
export const MAP_LINE_LIMIT = 200;
export const ABOUT_LIMIT = 120;
export const DEFAULT_INDEX_NAME = 'INDEX.md';
export const DEFAULT_ROOT_MAP_NAME = 'MAP.md';
export const DEFAULT_INDEX_THRESHOLD = 5;
export const DEFAULT_MAX_LINES = 400;
export const ROOT_INDEX_HEADING = 'Notes';

const OPTION_KEYS = new Set(['indexName', 'rootMapName', 'indexThreshold', 'maxLines', 'healthAsStored']);
const CONTROL = /[\u0000-\u001F\u007F-\u009F\u2028\u2029]/;
const LABEL_CHARS = /[\\[\]()*_`<>]/g;

export class AtlasError extends Error {
  constructor(message) {
    super(message);
    this.name = 'AtlasError';
  }
}

const fail = message => {
  throw new AtlasError(message);
};

const compareText = (a, b) => a < b ? -1 : a > b ? 1 : 0;

const plainObject = value => value !== null && typeof value === 'object' && !Array.isArray(value);

function show(value) {
  // A fresh global pattern so every control is escaped. CONTROL itself stays
  // non-global because a shared /g pattern would remember its last match.
  return String(value).replace(new RegExp(CONTROL.source, 'g'), ch => `\\u${ch.charCodeAt(0).toString(16).padStart(4, '0')}`);
}

/** A generated index starts with the header. A leading byte-order mark still counts. */
export function isGeneratedIndex(text) {
  if (typeof text !== 'string') return false;
  const stripped = text.startsWith('\uFEFF') ? text.slice(1) : text;
  return stripped.startsWith(GENERATED_HEADER);
}

function lineEnding(text) {
  return text.replace(/\r\n/g, '\n').replace(/\r/g, '\n');
}

/** Lines in the text. A trailing newline does not add an empty line. */
export function lineCount(text) {
  const normalized = lineEnding(text);
  if (normalized.length === 0) return 0;
  let count = 0;
  for (let i = 0; i < normalized.length; i += 1) if (normalized[i] === '\n') count += 1;
  if (!normalized.endsWith('\n')) count += 1;
  return count;
}

function normalizedText(text) {
  const stripped = text.startsWith('\uFEFF') ? text.slice(1) : text;
  return lineEnding(stripped).trim().toLowerCase();
}

function collapse(text) {
  return text.replace(/\s+/g, ' ').trim();
}

function cutWords(text, limit) {
  const flat = collapse(text);
  if (flat.length <= limit) return flat;
  const head = flat.slice(0, limit);
  const space = head.lastIndexOf(' ');
  if (space <= 0) return head;
  return head.slice(0, space);
}

function unquote(value) {
  if (value.length >= 2) {
    const first = value[0];
    const last = value[value.length - 1];
    if ((first === '"' && last === '"') || (first === "'" && last === "'")) return value.slice(1, -1);
  }
  return value;
}

function parentDir(notePath) {
  const slash = notePath.lastIndexOf('/');
  return slash < 0 ? '' : notePath.slice(0, slash);
}

function baseName(notePath) {
  const slash = notePath.lastIndexOf('/');
  return slash < 0 ? notePath : notePath.slice(slash + 1);
}

function fileTitle(notePath) {
  const name = baseName(notePath);
  return name.endsWith('.md') ? name.slice(0, -3) : name;
}

function indexPath(dir, indexName) {
  return dir ? `${dir}/${indexName}` : indexName;
}

function relativePath(fromDir, toPath) {
  const from = fromDir ? fromDir.split('/') : [];
  const to = toPath.split('/');
  let shared = 0;
  while (shared < from.length && shared < to.length && from[shared] === to[shared]) shared += 1;
  const parts = [];
  for (let i = shared; i < from.length; i += 1) parts.push('..');
  for (let i = shared; i < to.length; i += 1) parts.push(to[i]);
  return parts.join('/');
}

function encodeSegment(segment) {
  return encodeURIComponent(segment).replace(/[!'()*]/g, ch => `%${ch.charCodeAt(0).toString(16).toUpperCase()}`);
}

function encodePath(notePath) {
  return notePath.split('/').map(encodeSegment).join('/');
}

function escapeLabel(text) {
  return text.replace(LABEL_CHARS, ch => `\\${ch}`);
}

function linkLine(label, notePath) {
  return `- [${escapeLabel(label)}](${encodePath(notePath)})`;
}

function pathProblem(notePath) {
  if (notePath.length === 0) return 'it is empty';
  if (notePath.length > 4096) return 'it is longer than 4096 characters';
  if (notePath.includes('\\')) return 'it contains a backslash';
  if (CONTROL.test(notePath)) return 'it contains a control character';
  if (notePath.startsWith('/')) return 'it starts with "/"';
  if (!notePath.endsWith('.md')) return 'it does not end in .md';
  const segments = notePath.split('/');
  for (const segment of segments) {
    if (segment === '') return 'it contains an empty segment';
    if (segment === '.') return 'it contains a "." segment';
    if (segment === '..') return 'it contains ".."';
  }
  if (segments[segments.length - 1] === '.md') return 'it has no file name';
  return '';
}

function fileNameOption(value, label) {
  if (typeof value !== 'string') fail(`${label} must be text.`);
  for (const name of [value, value.normalize('NFC')]) {
    if (
      !name.endsWith('.md')
      || name.length === 3
      || name.includes('/')
      || name.includes('\\')
      || name.includes('..')
      || CONTROL.test(name)
    ) fail(`${label} must be a single .md file name.`);
  }
  return value;
}

function wholeOption(value, label) {
  if (typeof value !== 'number' || !Number.isInteger(value) || value < 0 || value > 1_000_000) {
    fail(`${label} must be a whole number from 0 to 1000000.`);
  }
  return value;
}

function readOptions(options) {
  if (options === undefined) options = {};
  if (!plainObject(options)) fail('Options must be an object.');
  for (const key of Object.keys(options)) {
    if (!OPTION_KEYS.has(key)) fail(`Unknown option "${show(key)}".`);
  }
  const indexName = options.indexName === undefined ? DEFAULT_INDEX_NAME : fileNameOption(options.indexName, 'indexName');
  const rootMapName = options.rootMapName === undefined ? DEFAULT_ROOT_MAP_NAME : fileNameOption(options.rootMapName, 'rootMapName');
  if (indexName.normalize('NFC') === rootMapName.normalize('NFC')) fail('indexName and rootMapName must be different files.');
  const indexThreshold = options.indexThreshold === undefined
    ? DEFAULT_INDEX_THRESHOLD
    : wholeOption(options.indexThreshold, 'indexThreshold');
  const maxLines = options.maxLines === undefined ? DEFAULT_MAX_LINES : wholeOption(options.maxLines, 'maxLines');
  if (options.healthAsStored !== undefined && typeof options.healthAsStored !== 'boolean') {
    fail('healthAsStored must be true or false.');
  }
  return { indexName, rootMapName, indexThreshold, maxLines, healthAsStored: options.healthAsStored === true };
}

function copyNotes(notes) {
  if (!Array.isArray(notes)) fail('Notes must be a list.');
  const copies = [];
  for (const note of notes) {
    if (!plainObject(note)) fail('Each note must be an object with path and text.');
    if (typeof note.path !== 'string') fail('Each note needs a path.');
    if (typeof note.text !== 'string') fail(`Refusing path "${show(note.path)}" because its text is not text.`);
    const problem = pathProblem(note.path);
    if (problem) fail(`Refusing path "${show(note.path)}" because ${problem}.`);
    copies.push({ path: note.path, text: note.text });
  }
  copies.sort((a, b) => compareText(a.path, b.path));
  const seen = new Set();
  for (const note of copies) {
    const key = note.path.normalize('NFC');
    if (seen.has(key)) fail(`Refusing path "${show(note.path)}" because it is listed twice.`);
    seen.add(key);
  }
  return copies;
}

function splitFrontMatter(text) {
  let raw = text.startsWith('\uFEFF') ? text.slice(1) : text;
  raw = lineEnding(raw);
  if (!raw.startsWith('---\n') && raw !== '---') return { meta: {}, body: raw };
  const lines = raw.split('\n');
  let end = -1;
  for (let i = 1; i < lines.length; i += 1) {
    if (lines[i] === '---') {
      end = i;
      break;
    }
  }
  if (end < 0) return { meta: {}, body: raw };
  const meta = {};
  for (const line of lines.slice(1, end)) {
    const match = /^([A-Za-z][A-Za-z0-9_-]*):\s*(.*)$/.exec(line);
    if (!match || Object.hasOwn(meta, match[1])) continue;
    meta[match[1]] = unquote(match[2].trim());
  }
  return { meta, body: lines.slice(end + 1).join('\n') };
}

function field(meta, key) {
  const value = meta[key];
  if (typeof value !== 'string') return '';
  return value.trim();
}

function firstHeading(body) {
  for (const line of body.split('\n')) {
    const match = /^( {0,3})# (.*)$/.exec(line);
    if (!match) continue;
    const title = match[2].replace(/\s+#+\s*$/, '').trim();
    if (title) return collapse(title);
  }
  return '';
}

function firstLine(body) {
  for (const line of body.split('\n')) {
    if (line.trim()) return collapse(line);
  }
  return '';
}

function aboutNote(note) {
  const { meta, body } = splitFrontMatter(note.text);
  const description = field(meta, 'description');
  if (description) return collapse(description);
  const heading = firstHeading(body);
  if (heading) return heading;
  const line = firstLine(body);
  if (line) return cutWords(line, ABOUT_LIMIT);
  return fileTitle(note.path);
}

function stripCode(text) {
  const lines = text.split('\n');
  let fence = null;
  const kept = [];
  for (const line of lines) {
    const match = /^( {0,3})(`{3,}|~{3,})(.*)$/.exec(line);
    if (match) {
      const marker = match[2];
      if (!fence) {
        fence = { char: marker[0], length: marker.length };
        kept.push('');
        continue;
      }
      if (marker[0] === fence.char && marker.length >= fence.length && match[3].trim() === '') {
        fence = null;
        kept.push('');
        continue;
      }
    }
    kept.push(fence ? '' : line);
  }
  return stripInline(kept.join('\n'));
}

function stripInline(text) {
  let out = '';
  for (let i = 0; i < text.length;) {
    if (text[i] !== '`') {
      out += text[i];
      i += 1;
      continue;
    }
    let length = 0;
    while (text[i + length] === '`') length += 1;
    const closer = text.indexOf('`'.repeat(length), i + length);
    if (closer < 0) {
      out += text.slice(i);
      break;
    }
    out += ' '.repeat(closer + length - i);
    i = closer + length;
  }
  return out;
}

function markdownDestinations(text) {
  const found = [];
  for (let i = 0; i < text.length; i += 1) {
    if (text[i] !== '[') continue;
    if (text[i + 1] === '[') continue;
    if (i > 0 && (text[i - 1] === '!' || text[i - 1] === '\\')) continue;
    const labelEnd = endOfLabel(text, i + 1);
    if (labelEnd < 0 || text[labelEnd + 1] !== '(') continue;
    const dest = readDestination(text, labelEnd + 2);
    if (!dest) continue;
    found.push(dest.value);
    i = dest.end;
  }
  return found;
}

function endOfLabel(text, start) {
  let depth = 1;
  for (let i = start; i < text.length; i += 1) {
    if (text[i] === '\\') {
      i += 1;
      continue;
    }
    if (text[i] === '[') {
      depth += 1;
      continue;
    }
    if (text[i] === ']') {
      depth -= 1;
      if (depth === 0) return i;
      continue;
    }
    // A soft line break stays inside the label. A blank line ends it.
    if (text[i] === '\n' && text[i + 1] === '\n') return -1;
  }
  return -1;
}

function readDestination(text, start) {
  let i = start;
  while (text[i] === ' ' || text[i] === '\t') i += 1;
  if (text[i] === '<') {
    const end = text.indexOf('>', i + 1);
    if (end < 0) return null;
    const close = text.indexOf(')', end + 1);
    if (close < 0) return null;
    return { value: text.slice(i + 1, end).trim(), end: close };
  }
  let value = '';
  let depth = 0;
  let j = i;
  while (j < text.length) {
    const ch = text[j];
    if (ch === '\\' && j + 1 < text.length) {
      value += text[j + 1];
      j += 2;
      continue;
    }
    if (ch === ' ' || ch === '\t' || ch === '\n') break;
    if (ch === '(') {
      depth += 1;
      value += ch;
      j += 1;
      continue;
    }
    if (ch === ')') {
      if (depth === 0) break;
      depth -= 1;
      value += ch;
      j += 1;
      continue;
    }
    value += ch;
    j += 1;
  }
  if (!value || depth !== 0) return null;
  const close = text[j] === ')' ? j : text.indexOf(')', j);
  if (close < 0) return null;
  return { value, end: close };
}

function wikiTargets(text) {
  const found = [];
  const pattern = /\[\[([^\[\]|#]+?)(#[^\[\]|]*)?(?:\|[^\[\]]*)?\]\]/g;
  for (const match of text.matchAll(pattern)) {
    const name = match[1].trim();
    if (name) found.push(name);
  }
  return found;
}

function parseRelative(dest) {
  const trimmed = dest.trim();
  if (!trimmed || trimmed.startsWith('//') || trimmed.startsWith('/')) return { ignore: true };
  if (/^[a-zA-Z][a-zA-Z0-9+.-]*:/.test(trimmed)) return { ignore: true };
  const segments = [];
  for (const partOfDest of trimmed.split('/')) {
    const hash = partOfDest.indexOf('#');
    const query = partOfDest.indexOf('?');
    let cut = -1;
    if (hash >= 0) cut = hash;
    if (query >= 0 && (cut < 0 || query < cut)) cut = query;
    const part = cut >= 0 ? partOfDest.slice(0, cut) : partOfDest;
    if (part !== '' && part !== '.') {
      let decoded;
      try {
        decoded = decodeURIComponent(part);
      } catch {
        return { broken: true };
      }
      if (
        decoded.includes('/')
        || decoded.includes('\\')
        || decoded === ''
        || CONTROL.test(decoded)
      ) return { broken: true };
      segments.push(decoded);
    }
    if (cut >= 0) break;
  }
  if (!segments.length) return { ignore: true };
  return { segments };
}

function resolveSegments(fromDir, segments) {
  const stack = fromDir ? fromDir.split('/') : [];
  for (const segment of segments) {
    if (segment === '..') {
      if (!stack.length) return '';
      stack.pop();
      continue;
    }
    stack.push(segment);
  }
  return stack.join('/');
}

function refsIn(notePath, text) {
  const { body } = splitFrontMatter(text);
  const source = stripCode(body);
  const broken = [];
  const pointsAt = [];
  for (const dest of markdownDestinations(source)) {
    const parsed = parseRelative(dest);
    if (parsed.ignore) continue;
    if (parsed.broken) {
      broken.push(dest.trim());
      continue;
    }
    const resolved = resolveSegments(parentDir(notePath), parsed.segments);
    if (!resolved || !resolved.endsWith('.md')) {
      if (!resolved) broken.push(dest.trim());
      continue;
    }
    pointsAt.push({ target: resolved, detail: dest.trim() });
  }
  for (const name of wikiTargets(source)) {
    pointsAt.push({ wiki: name.normalize('NFC'), detail: `[[${name}]]` });
  }
  return { broken, pointsAt };
}

/**
 * Rebuild folder indexes and the root map, and check links, orphans,
 * duplicates, length, and hand-made indexes.
 *
 * @param {{ path: string, text: string }[]} notes
 * @param {{ indexName?: string, rootMapName?: string, indexThreshold?: number, maxLines?: number }} [options]
 */
export function buildAtlas(notes, options) {
  const settings = readOptions(options);
  const copies = copyNotes(notes);
  const { indexName, rootMapName, indexThreshold, maxLines, healthAsStored } = settings;
  const byPath = new Map(copies.map(note => [note.path, note]));
  const isIndex = notePath => baseName(notePath) === indexName;
  const isMap = notePath => notePath === rootMapName;
  const content = copies.filter(note => !isIndex(note.path) && !isMap(note.path));
  const notesByDir = new Map();
  for (const note of content) {
    const dir = parentDir(note.path);
    if (!notesByDir.has(dir)) notesByDir.set(dir, []);
    notesByDir.get(dir).push(note);
  }

  const directCount = dir => notesByDir.get(dir)?.length ?? 0;
  const keptIndex = dir => {
    if (directCount(dir) > indexThreshold) return true;
    const existing = byPath.get(indexPath(dir, indexName));
    return existing !== undefined && !isGeneratedIndex(existing.text);
  };

  const directories = new Set();
  const addDir = dir => {
    let current = dir;
    directories.add(current);
    while (current) {
      const slash = current.lastIndexOf('/');
      current = slash < 0 ? '' : current.slice(0, slash);
      directories.add(current);
    }
  };
  for (const note of content) addDir(parentDir(note.path));
  for (const note of copies) if (isIndex(note.path)) addDir(parentDir(note.path));

  function childDirs(dir) {
    const prefix = dir ? `${dir}/` : '';
    const children = new Set();
    for (const candidate of directories) {
      if (candidate === dir || !candidate.startsWith(prefix)) continue;
      const rest = candidate.slice(prefix.length);
      const slash = rest.indexOf('/');
      const name = slash < 0 ? rest : rest.slice(0, slash);
      if (name) children.add(prefix + name);
    }
    return [...children].sort(compareText);
  }

  function listingLines(dir, fromDir) {
    const lines = [];
    const own = (notesByDir.get(dir) || []).slice().sort((a, b) => compareText(a.path, b.path));
    for (const note of own) lines.push(linkLine(aboutNote(note), relativePath(fromDir, note.path)));
    for (const child of childDirs(dir)) {
      if (keptIndex(child)) {
        const label = child.split('/').pop();
        lines.push(linkLine(label, relativePath(fromDir, indexPath(child, indexName))));
      } else {
        lines.push(...listingLines(child, fromDir));
      }
    }
    return lines;
  }

  function renderIndex(dir) {
    const heading = dir === '' ? ROOT_INDEX_HEADING : dir.split('/').pop();
    const lines = listingLines(dir, dir);
    const list = lines.length ? `${lines.join('\n')}\n` : '';
    return `${GENERATED_HEADER}\n# ${heading}\n\n${list}`;
  }

  function folderHasNotes(dir) {
    const prefix = `${dir}/`;
    return content.some(note => note.path.startsWith(prefix));
  }

  // The root map is one line per root note and one line per top-level folder.
  // A folder index may still expand a subfolder that has no index of its own.
  function rootMapLines() {
    const lines = [];
    const rootNotes = (notesByDir.get('') || []).slice().sort((a, b) => compareText(a.path, b.path));
    for (const note of rootNotes) lines.push(linkLine(aboutNote(note), relativePath('', note.path)));
    for (const child of childDirs('')) {
      if (!keptIndex(child) && !folderHasNotes(child)) continue;
      const label = child.split('/').pop();
      const target = keptIndex(child) ? indexPath(child, indexName) : `${child}/`;
      lines.push(linkLine(label, relativePath('', target)));
    }
    return lines;
  }

  function renderMap(existing) {
    const lines = rootMapLines();
    const generated = lines.length ? `${MAP_MARKER}\n${lines.join('\n')}\n` : `${MAP_MARKER}\n`;
    if (existing === undefined) return generated;
    const markerAt = existing.indexOf(MAP_MARKER);
    if (markerAt < 0) {
      if (existing.length === 0) return generated;
      return existing.endsWith('\n') ? existing + generated : `${existing}\n${generated}`;
    }
    return existing.slice(0, markerAt) + generated;
  }

  const writes = [];
  const unchanged = [];
  const consider = (notePath, text) => {
    const existing = byPath.get(notePath);
    if (existing && existing.text === text) unchanged.push(notePath);
    else writes.push({ path: notePath, text });
  };

  for (const dir of [...notesByDir.keys()].sort(compareText)) {
    if (directCount(dir) <= indexThreshold) continue;
    const notePath = indexPath(dir, indexName);
    const existing = byPath.get(notePath);
    if (existing && !isGeneratedIndex(existing.text)) continue;
    consider(notePath, renderIndex(dir));
  }
  consider(rootMapName, renderMap(byPath.get(rootMapName)?.text));

  const removes = [];
  for (const note of copies) {
    if (!isIndex(note.path) || !isGeneratedIndex(note.text)) continue;
    if (directCount(parentDir(note.path)) > indexThreshold) continue;
    removes.push(note.path);
  }

  const conflicts = [];
  for (const note of copies) {
    if (!isIndex(note.path) || isGeneratedIndex(note.text)) continue;
    conflicts.push({
      path: note.path,
      detail: 'This index was written by hand, so it was left as it is.',
    });
  }

  writes.sort((a, b) => compareText(a.path, b.path));
  removes.sort(compareText);
  unchanged.sort(compareText);
  conflicts.sort((a, b) => compareText(a.path, b.path) || compareText(a.detail, b.detail));

  const files = new Map(copies.map(note => [note.path, note.text]));
  // healthAsStored reports the notes as given. The command uses it when a
  // case collision leaves every planned write and removal unapplied.
  if (!healthAsStored) {
    for (const notePath of removes) files.delete(notePath);
    for (const item of writes) files.set(item.path, item.text);
  }
  // Links may use either Unicode spelling. The stored path stays the one we
  // were given, which is the spelling on disk when the command scanned it.
  const storedPath = new Map();
  for (const notePath of files.keys()) storedPath.set(notePath.normalize('NFC'), notePath);
  const resolveStored = target => files.has(target) ? target : storedPath.get(target.normalize('NFC'));

  const wikiNames = new Map();
  const addName = (name, notePath) => {
    if (!name) return;
    const key = name.normalize('NFC');
    if (!wikiNames.has(key)) wikiNames.set(key, new Set());
    wikiNames.get(key).add(notePath);
  };
  for (const [notePath, text] of files) {
    addName(fileTitle(notePath), notePath);
    addName(notePath.slice(0, -3), notePath);
    addName(field(splitFrontMatter(text).meta, 'name'), notePath);
  }

  const health = [];
  const seenBroken = new Set();
  const incoming = new Set();
  const sortedFiles = [...files.keys()].sort(compareText);
  for (const notePath of sortedFiles) {
    const text = files.get(notePath);
    // The map and generated indexes are navigation. A link that exists only
    // there does not stop a note from being an orphan. Broken links in them
    // are still reported.
    const countsAsLinker = notePath !== rootMapName && !(isIndex(notePath) && isGeneratedIndex(text));
    const refs = refsIn(notePath, text);
    for (const detail of refs.broken) pushBroken(health, seenBroken, notePath, detail);
    for (const point of refs.pointsAt) {
      if (point.wiki !== undefined) {
        const matches = wikiNames.get(point.wiki);
        if (!matches || matches.size === 0) pushBroken(health, seenBroken, notePath, point.detail);
        else if (countsAsLinker) for (const target of matches) if (target !== notePath) incoming.add(target);
        continue;
      }
      const stored = resolveStored(point.target);
      if (!stored) pushBroken(health, seenBroken, notePath, point.detail);
      else if (countsAsLinker && stored !== notePath) incoming.add(stored);
    }
  }

  for (const note of content) {
    if (incoming.has(note.path)) continue;
    health.push({ kind: 'orphan', path: note.path, detail: 'No other note links to this one.' });
  }

  const textGroups = groupNotes(content, note => normalizedText(note.text));
  const textKeys = new Set(textGroups.map(paths => paths.join('\0')));
  for (const paths of textGroups) {
    health.push({ kind: 'duplicate', path: paths[0], detail: `Same text: ${paths.join(', ')}` });
  }
  for (const paths of groupNotes(content, note => aboutNote(note).toLowerCase())) {
    if (textKeys.has(paths.join('\0'))) continue;
    health.push({ kind: 'duplicate', path: paths[0], detail: `Same about line: ${paths.join(', ')}` });
  }

  for (const note of content) {
    const count = lineCount(note.text);
    if (count > maxLines) {
      health.push({
        kind: 'too-long',
        path: note.path,
        detail: `${count} lines is over the limit of ${maxLines}.`,
      });
    }
  }
  for (const note of copies) {
    if (!isIndex(note.path) || isGeneratedIndex(note.text)) continue;
    const count = lineCount(note.text);
    if (count > maxLines) {
      health.push({
        kind: 'too-long',
        path: note.path,
        detail: `${count} lines is over the limit of ${maxLines}.`,
      });
    }
  }
  const mapText = files.get(rootMapName) ?? '';
  const mapLines = lineCount(mapText);
  if (mapLines > MAP_LINE_LIMIT) {
    health.push({
      kind: 'too-long',
      path: rootMapName,
      detail: `${mapLines} lines is over the limit of ${MAP_LINE_LIMIT}.`,
    });
  }

  for (const conflict of conflicts) {
    health.push({ kind: 'conflict', path: conflict.path, detail: conflict.detail });
  }

  health.sort((a, b) => compareText(a.kind, b.kind) || compareText(a.path, b.path) || compareText(a.detail, b.detail));

  const folderDirs = new Set();
  const markFolder = dir => {
    let current = dir;
    folderDirs.add(current);
    while (current) {
      const slash = current.lastIndexOf('/');
      current = slash < 0 ? '' : current.slice(0, slash);
      folderDirs.add(current);
    }
  };
  for (const dir of notesByDir.keys()) if (directCount(dir) > 0) markFolder(dir);
  for (const note of copies) {
    if (isIndex(note.path) && keptIndex(parentDir(note.path))) markFolder(parentDir(note.path));
  }

  const kindCount = kind => health.filter(item => item.kind === kind).length;
  const counts = {
    notes: content.length,
    folders: folderDirs.size,
    indexesWritten: writes.filter(item => isIndex(item.path)).length,
    indexesRemoved: removes.length,
    mapWritten: writes.some(item => item.path === rootMapName) ? 1 : 0,
    'broken-link': kindCount('broken-link'),
    conflict: kindCount('conflict'),
    duplicate: kindCount('duplicate'),
    orphan: kindCount('orphan'),
    'too-long': kindCount('too-long'),
  };

  return { writes, removes, unchanged, conflicts, health, counts };
}

function pushBroken(health, seen, notePath, detail) {
  const key = `${notePath}\0${detail}`;
  if (seen.has(key)) return;
  seen.add(key);
  health.push({ kind: 'broken-link', path: notePath, detail });
}

function groupNotes(notes, keyOf) {
  const grouped = new Map();
  for (const note of notes) {
    const key = keyOf(note);
    if (!grouped.has(key)) grouped.set(key, []);
    grouped.get(key).push(note.path);
  }
  const groups = [];
  for (const paths of grouped.values()) {
    if (paths.length < 2) continue;
    paths.sort(compareText);
    groups.push(paths);
  }
  groups.sort((a, b) => compareText(a[0], b[0]) || compareText(a.join('\0'), b.join('\0')));
  return groups;
}

/** Paths that differ only by case. The command uses this on macOS. */
export function caseFoldClash(paths) {
  const groups = new Map();
  for (const notePath of paths) {
    const key = notePath.toLowerCase();
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push(notePath);
  }
  const clashes = [];
  for (const group of groups.values()) {
    const unique = [...new Set(group)].sort(compareText);
    if (unique.length > 1) clashes.push(unique.join(' and '));
  }
  clashes.sort(compareText);
  return clashes;
}
