/**
 * Plan repairs for markdown links that broke because a note moved.
 * Notes go in, and a repair list comes out. This file reads and writes
 * nothing. The same notes always produce the same result.
 */

import { createHash } from 'node:crypto';

const GENERATED_HEADER = '<!-- Generated by atlas-index. Do not edit by hand. -->';
const MAP_MARKER = '<!-- atlas-index:start -->';
const MAP_PATH = 'MAP.md';
const CONTROL = /[\u0000-\u001F\u007F-\u009F\u2028\u2029]/;
const SCHEME = /^[a-zA-Z][a-zA-Z0-9+.-]*:/;

const NO_MATCH = 'No note has this name.';
const MANY = 'More than one note has this name.';
const SELF = 'This link points at its own note.';
const NO_SNAPSHOT = 'No snapshot yet, so run --record before a later move can be repaired.';
const NOT_A_MOVE = 'The snapshot does not show that this note moved.';
const UNSAFE_WIKI = "This note's name is not a safe unique wiki link.";
const UNREADABLE = "This link's target cannot be read.";
const ALREADY = 'The link text already matches the note, but it still does not resolve.';

export class LinkRepairError extends Error {
  constructor(message) {
    super(message);
    this.name = 'LinkRepairError';
  }
}

const fail = message => {
  throw new LinkRepairError(message);
};

const compareText = (a, b) => a < b ? -1 : a > b ? 1 : 0;

const plainObject = value => value !== null && typeof value === 'object' && !Array.isArray(value);

function show(value) {
  return String(value).replace(new RegExp(CONTROL.source, 'g'), ch => `\\u${ch.charCodeAt(0).toString(16).padStart(4, '0')}`);
}

/** SHA-256 of the note text, as lowercase hex. The command hashes the same UTF-8 bytes. */
export function sha256Text(text) {
  return createHash('sha256').update(text, 'utf8').digest('hex');
}

export function isGeneratedIndex(text) {
  if (typeof text !== 'string') return false;
  const stripped = text.startsWith('\uFEFF') ? text.slice(1) : text;
  return stripped.startsWith(GENERATED_HEADER);
}

function pathProblem(notePath) {
  if (notePath.length === 0) return 'it is empty';
  if (notePath.length > 4096) return 'it is longer than 4096 characters';
  if (notePath.includes('\\')) return 'it contains a backslash';
  if (CONTROL.test(notePath)) return 'it contains a control character';
  if (notePath.startsWith('/')) return 'it starts with "/"';
  if (!notePath.endsWith('.md')) return 'it does not end in .md';
  const segments = notePath.split('/');
  for (const segment of segments) {
    if (segment === '') return 'it contains an empty segment';
    if (segment === '.') return 'it contains a "." segment';
    if (segment === '..') return 'it contains ".."';
  }
  if (segments[segments.length - 1] === '.md') return 'it has no file name';
  return '';
}

function copyNotes(notes) {
  if (!Array.isArray(notes)) fail('Notes must be a list.');
  const copies = [];
  for (const note of notes) {
    if (!plainObject(note)) fail('Each note must be an object with path and text.');
    if (typeof note.path !== 'string') fail('Each note needs a path.');
    if (typeof note.text !== 'string') fail(`Refusing path "${show(note.path)}" because its text is not text.`);
    const problem = pathProblem(note.path);
    if (problem) fail(`Refusing path "${show(note.path)}" because ${problem}.`);
    copies.push({ path: note.path, text: note.text });
  }
  copies.sort((a, b) => compareText(a.path, b.path));
  const seen = new Set();
  for (const note of copies) {
    const key = note.path.normalize('NFC');
    if (seen.has(key)) fail(`Refusing path "${show(note.path)}" because it is listed twice.`);
    seen.add(key);
  }
  return copies;
}

function readSnapshot(snapshot) {
  if (snapshot === null) return null;
  if (!plainObject(snapshot)) fail('Snapshot must be an object or null.');
  for (const key of Object.keys(snapshot)) {
    if (key !== 'notes') fail(`Unknown snapshot field "${show(key)}".`);
  }
  if (!Array.isArray(snapshot.notes)) fail('Snapshot notes must be a list.');
  const notes = [];
  const seen = new Set();
  for (const note of snapshot.notes) {
    if (!plainObject(note)) fail('Each snapshot note needs a path and a sha256.');
    for (const key of Object.keys(note)) {
      if (key !== 'path' && key !== 'sha256') fail(`Unknown snapshot field "${show(key)}".`);
    }
    if (typeof note.path !== 'string' || typeof note.sha256 !== 'string') {
      fail('Each snapshot note needs a path and a sha256.');
    }
    const problem = pathProblem(note.path);
    if (problem) fail(`Refusing snapshot path "${show(note.path)}" because ${problem}.`);
    if (!/^[0-9a-f]{64}$/.test(note.sha256)) {
      fail(`Snapshot hash for "${show(note.path)}" must be 64 lowercase hex characters.`);
    }
    const key = note.path.normalize('NFC');
    if (seen.has(key)) fail(`Snapshot path "${show(note.path)}" is listed twice.`);
    seen.add(key);
    notes.push({ path: note.path, sha256: note.sha256 });
  }
  notes.sort((a, b) => compareText(a.path, b.path));
  return { notes };
}

function parentDir(notePath) {
  const slash = notePath.lastIndexOf('/');
  return slash < 0 ? '' : notePath.slice(0, slash);
}

function fileTitle(notePath) {
  const slash = notePath.lastIndexOf('/');
  const name = slash < 0 ? notePath : notePath.slice(slash + 1);
  return name.endsWith('.md') ? name.slice(0, -3) : name;
}

function nameKey(name) {
  return name.normalize('NFC').toLowerCase();
}

function relativePath(fromDir, toPath) {
  const from = fromDir ? fromDir.split('/') : [];
  const to = toPath.split('/');
  let shared = 0;
  while (shared < from.length && shared < to.length && from[shared] === to[shared]) shared += 1;
  const parts = [];
  for (let i = shared; i < from.length; i += 1) parts.push('..');
  for (let i = shared; i < to.length; i += 1) parts.push(to[i]);
  return parts.join('/');
}

function encodeSegment(segment) {
  return encodeURIComponent(segment).replace(/[!'()*]/g, ch => `%${ch.charCodeAt(0).toString(16).toUpperCase()}`);
}

function encodePath(notePath) {
  return notePath.split('/').map(encodeSegment).join('/');
}

function normalize(text) {
  let i = text.startsWith('\uFEFF') ? 1 : 0;
  let norm = '';
  const map = [];
  while (i < text.length) {
    if (text[i] === '\r') {
      map.push(i);
      norm += '\n';
      i += 1;
      if (text[i] === '\n') i += 1;
      continue;
    }
    map.push(i);
    norm += text[i];
    i += 1;
  }
  return { norm, map };
}

function bodyStart(norm) {
  if (!norm.startsWith('---\n') && norm !== '---') return 0;
  let pos = 0;
  let lineIndex = 0;
  while (pos <= norm.length) {
    const nl = norm.indexOf('\n', pos);
    const line = norm.slice(pos, nl < 0 ? norm.length : nl);
    const next = nl < 0 ? norm.length : nl + 1;
    if (lineIndex > 0 && line === '---') return next;
    if (nl < 0) break;
    pos = next;
    lineIndex += 1;
  }
  return 0;
}

function unquote(value) {
  if (value.length >= 2) {
    const first = value[0];
    const last = value[value.length - 1];
    if ((first === '"' && last === '"') || (first === "'" && last === "'")) return value.slice(1, -1);
  }
  return value;
}

function frontName(text) {
  const { norm } = normalize(text);
  if (!norm.startsWith('---\n') && norm !== '---') return '';
  const lines = norm.split('\n');
  let end = -1;
  for (let i = 1; i < lines.length; i += 1) {
    if (lines[i] === '---') {
      end = i;
      break;
    }
  }
  if (end < 0) return '';
  const meta = {};
  for (const line of lines.slice(1, end)) {
    const match = /^([A-Za-z][A-Za-z0-9_-]*):\s*(.*)$/.exec(line);
    if (!match || Object.hasOwn(meta, match[1])) continue;
    meta[match[1]] = unquote(match[2].trim());
  }
  return typeof meta.name === 'string' ? meta.name.trim() : '';
}

function findCloser(chars, from, length) {
  for (let i = from; i + length <= chars.length; i += 1) {
    let same = true;
    for (let j = 0; j < length; j += 1) {
      if (chars[i + j] !== '`') {
        same = false;
        break;
      }
    }
    if (same) return i;
  }
  return -1;
}

function maskSearchFixed(norm, start, end) {
  const chars = [];
  for (let i = 0; i < norm.length; i += 1) chars.push(i >= start && i < end ? norm[i] : ' ');
  let fence = null;
  let lineStart = 0;
  const blankLine = lineEnd => {
    for (let i = lineStart; i < lineEnd; i += 1) chars[i] = ' ';
  };
  for (let i = 0; i <= chars.length; i += 1) {
    if (i !== chars.length && chars[i] !== '\n') continue;
    const line = chars.slice(lineStart, i).join('');
    const match = /^( {0,3})(`{3,}|~{3,})(.*)$/.exec(line);
    if (match) {
      const marker = match[2];
      if (!fence) {
        fence = { char: marker[0], length: marker.length };
        blankLine(i);
      } else if (marker[0] === fence.char && marker.length >= fence.length && match[3].trim() === '') {
        fence = null;
        blankLine(i);
      } else if (fence) blankLine(i);
    } else if (fence) blankLine(i);
    lineStart = i + 1;
  }
  const out = [];
  for (let i = 0; i < chars.length;) {
    if (chars[i] !== '`') {
      out.push(chars[i]);
      i += 1;
      continue;
    }
    let length = 0;
    while (chars[i + length] === '`') length += 1;
    const closer = findCloser(chars, i + length, length);
    if (closer < 0) {
      while (i < chars.length) out.push(chars[i++]);
      break;
    }
    for (let j = i; j < closer + length; j += 1) out.push(' ');
    i = closer + length;
  }
  return out.join('');
}

function endOfLabel(text, start) {
  let depth = 1;
  for (let i = start; i < text.length; i += 1) {
    if (text[i] === '\\') {
      i += 1;
      continue;
    }
    if (text[i] === '[') {
      depth += 1;
      continue;
    }
    if (text[i] === ']') {
      depth -= 1;
      if (depth === 0) return i;
      continue;
    }
    if (text[i] === '\n' && text[i + 1] === '\n') return -1;
  }
  return -1;
}

function readDestination(text, start) {
  let i = start;
  while (text[i] === ' ' || text[i] === '\t') i += 1;
  if (text[i] === '<') {
    const end = text.indexOf('>', i + 1);
    if (end < 0) return null;
    const close = text.indexOf(')', end + 1);
    if (close < 0) return null;
    return {
      value: text.slice(i + 1, end).trim(),
      rawStart: i,
      rawEnd: end + 1,
      end: close,
      bracket: true,
    };
  }
  let value = '';
  let depth = 0;
  let j = i;
  while (j < text.length) {
    const ch = text[j];
    if (ch === '\\' && j + 1 < text.length) {
      value += text[j + 1];
      j += 2;
      continue;
    }
    if (ch === ' ' || ch === '\t' || ch === '\n') break;
    if (ch === '(') {
      depth += 1;
      value += ch;
      j += 1;
      continue;
    }
    if (ch === ')') {
      if (depth === 0) break;
      depth -= 1;
      value += ch;
      j += 1;
      continue;
    }
    value += ch;
    j += 1;
  }
  if (!value || depth !== 0) return null;
  const close = text[j] === ')' ? j : text.indexOf(')', j);
  if (close < 0) return null;
  return { value, rawStart: i, rawEnd: j, end: close, bracket: false };
}

function analyzeDest(value) {
  const trimmed = value.trim();
  if (!trimmed || trimmed.startsWith('//') || trimmed.startsWith('/')) return { ignore: true };
  if (SCHEME.test(trimmed)) return { ignore: true };
  const segments = [];
  let index = 0;
  while (index <= trimmed.length) {
    const slash = trimmed.indexOf('/', index);
    const partEnd = slash < 0 ? trimmed.length : slash;
    const part = trimmed.slice(index, partEnd);
    const hash = part.indexOf('#');
    const query = part.indexOf('?');
    let cut = -1;
    if (hash >= 0) cut = hash;
    if (query >= 0 && (cut < 0 || query < cut)) cut = query;
    const piece = cut >= 0 ? part.slice(0, cut) : part;
    if (piece !== '' && piece !== '.') {
      let decoded;
      try {
        decoded = decodeURIComponent(piece);
      } catch {
        return { broken: true };
      }
      if (decoded.includes('/') || decoded.includes('\\') || decoded === '' || CONTROL.test(decoded)) {
        return { broken: true };
      }
      segments.push(decoded);
    }
    if (cut >= 0) {
      if (!segments.length) return { ignore: true };
      return { segments, suffix: trimmed.slice(index + cut) };
    }
    if (slash < 0) break;
    index = slash + 1;
  }
  if (!segments.length) return { ignore: true };
  return { segments, suffix: '' };
}

function resolveSegments(fromDir, segments) {
  const stack = fromDir ? fromDir.split('/') : [];
  for (const segment of segments) {
    if (segment === '..') {
      if (!stack.length) return '';
      stack.pop();
      continue;
    }
    stack.push(segment);
  }
  return stack.join('/');
}

function fileNameFrom(segments) {
  const last = segments.length ? segments[segments.length - 1] : '';
  if (!last || last === '..' || last === '.') return '';
  return last.endsWith('.md') ? last.slice(0, -3) : '';
}

function origSpan(map, text, start, end) {
  const from = map[start];
  const to = end < map.length ? map[end] : text.length;
  return { start: from, end: to };
}

function lineAndColumn(text, index) {
  let line = 1;
  let column = 1;
  for (let i = 0; i < index; i += 1) {
    if (text[i] === '\r') {
      line += 1;
      column = 1;
      if (text[i + 1] === '\n') i += 1;
      continue;
    }
    if (text[i] === '\n') {
      line += 1;
      column = 1;
      continue;
    }
    column += 1;
  }
  return { line, column };
}

function linksIn(note) {
  if (isGeneratedIndex(note.text)) return [];
  const { norm, map } = normalize(note.text);
  const start = bodyStart(norm);
  let end = norm.length;
  if (note.path === MAP_PATH) {
    const marker = norm.indexOf(MAP_MARKER);
    if (marker >= 0) end = marker;
  }
  if (start >= end) return [];
  const view = maskSearchFixed(norm, start, end);
  const found = [];
  for (let i = 0; i < view.length; i += 1) {
    if (view[i] !== '[') continue;
    if (view[i + 1] === '[') continue;
    if (i > 0 && (view[i - 1] === '!' || view[i - 1] === '\\')) continue;
    const labelEnd = endOfLabel(view, i + 1);
    if (labelEnd < 0 || view[labelEnd + 1] !== '(') continue;
    const dest = readDestination(view, labelEnd + 2);
    if (!dest) continue;
    const analyzed = analyzeDest(dest.value);
    const where = origSpan(map, note.text, i, dest.end + 1);
    const raw = origSpan(map, note.text, dest.rawStart, dest.rawEnd);
    const place = lineAndColumn(note.text, where.start);
    const link = {
      kind: 'md',
      line: place.line,
      column: place.column,
      start: raw.start,
      end: raw.end,
      linkStart: where.start,
      linkEnd: where.end,
      from: note.text.slice(raw.start, raw.end),
      link: note.text.slice(where.start, where.end),
      detail: dest.value.trim(),
      suffix: analyzed.suffix || '',
      fileName: '',
      resolved: '',
      unreadable: false,
      ignore: false,
      wikiName: '',
    };
    if (analyzed.ignore) link.ignore = true;
    else if (analyzed.broken) link.unreadable = true;
    else {
      link.fileName = fileNameFrom(analyzed.segments);
      link.resolved = resolveSegments(parentDir(note.path), analyzed.segments);
      if (!link.resolved) link.unreadable = false;
    }
    if (!link.ignore) found.push(link);
    i = dest.end;
  }
  const wiki = /\[\[([^\[\]|#]+?)(#[^\[\]|]*)?(?:\|[^\[\]]*)?\]\]/g;
  for (const match of view.matchAll(wiki)) {
    const raw = match[1];
    const name = raw.trim();
    if (!name) continue;
    const leading = raw.length - raw.trimStart().length;
    const trailing = raw.length - raw.trimEnd().length;
    const coreStart = match.index + 2 + leading;
    const coreEnd = match.index + 2 + raw.length - trailing;
    const nameSpan = origSpan(map, note.text, coreStart, coreEnd);
    const linkSpan = origSpan(map, note.text, match.index, match.index + match[0].length);
    const place = lineAndColumn(note.text, linkSpan.start);
    const last = name.split('/').pop();
    const fileName = last.toLowerCase().endsWith('.md') ? last.slice(0, -3) : last;
    found.push({
      kind: 'wiki',
      line: place.line,
      column: place.column,
      start: nameSpan.start,
      end: nameSpan.end,
      linkStart: linkSpan.start,
      linkEnd: linkSpan.end,
      from: note.text.slice(nameSpan.start, nameSpan.end),
      link: note.text.slice(linkSpan.start, linkSpan.end),
      detail: `[[${name}]]`,
      suffix: '',
      fileName,
      resolved: '',
      unreadable: false,
      ignore: false,
      wikiName: name,
    });
  }
  found.sort((a, b) => a.start - b.start || a.column - b.column);
  return found;
}

function brokenMarkdown(link, paths) {
  if (link.ignore) return false;
  if (link.unreadable) return true;
  if (!link.resolved || !link.resolved.endsWith('.md')) return !link.resolved;
  return !storedPath(paths, link.resolved);
}

function wikiHits(name, notes) {
  const key = name.normalize('NFC');
  const hits = [];
  for (const note of notes) {
    const title = fileTitle(note.path).normalize('NFC');
    const stem = note.path.slice(0, -3).normalize('NFC');
    const meta = frontName(note.text).normalize('NFC');
    if (title === key || stem === key || (meta && meta === key)) hits.push(note.path);
  }
  return [...new Set(hits)];
}

function storedPath(paths, target) {
  if (paths.has(target)) return target;
  const want = target.normalize('NFC');
  for (const notePath of paths) {
    if (notePath.normalize('NFC') === want) return notePath;
  }
  return '';
}

function safeWiki(name) {
  return Boolean(name) && !/[#|[\]\n\r]/.test(name);
}

function oldSnapshotPath(link, snapshot) {
  if (!snapshot) return '';
  if (link.kind === 'md') {
    if (!link.resolved || !link.resolved.endsWith('.md')) return '';
    if (pathProblem(link.resolved)) return '';
    return link.resolved;
  }
  if (link.wikiName.includes('/')) {
    const old = link.wikiName.endsWith('.md') ? link.wikiName : `${link.wikiName}.md`;
    if (pathProblem(old)) return '';
    return old;
  }
  const key = nameKey(link.fileName);
  const matches = snapshot.notes.filter(note => nameKey(fileTitle(note.path)) === key);
  if (matches.length !== 1) return '';
  return matches[0].path;
}

function snapshotNote(snapshot, notePath) {
  if (!snapshot) return undefined;
  const want = notePath.normalize('NFC');
  return snapshot.notes.find(note => note.path.normalize('NFC') === want);
}

function hidden(record, extra) {
  for (const [key, value] of Object.entries(extra)) {
    Object.defineProperty(record, key, { value, enumerable: false });
  }
  return record;
}

function needsYou(note, link, candidates, reason) {
  return hidden({
    path: note.path,
    line: link.line,
    link: link.link,
    candidates: candidates.map(item => item.path).sort(compareText),
    reason,
  }, {
    column: link.column,
    detail: link.detail,
  });
}

function candidateNotes(fileName, notes) {
  if (!fileName) return [];
  const key = nameKey(fileName);
  return notes.filter(note => !isGeneratedIndex(note.text) && nameKey(fileTitle(note.path)) === key);
}

function wikiReplacement(note, link, dest, notes) {
  const fileName = fileTitle(dest.path);
  const stem = dest.path.slice(0, -3);
  const unique = name => {
    const hits = wikiHits(name, notes);
    return hits.length === 1 && hits[0] === dest.path;
  };
  if (safeWiki(fileName) && unique(fileName)) return fileName;
  if (safeWiki(stem) && unique(stem)) return stem;
  return '';
}

/**
 * Plan link repairs. `snapshot` is `{ notes: [{ path, sha256 }] }` or null.
 * Generated indexes are skipped. In MAP.md, only the hand-written part
 * before the atlas-index marker is read.
 *
 * @param {{ path: string, text: string }[]} notes
 * @param {{ notes: { path: string, sha256: string }[] } | null} snapshot
 */
export function planRepairs(notes, snapshot) {
  const copies = copyNotes(notes);
  const saved = readSnapshot(snapshot);
  const paths = new Set(copies.map(note => note.path));
  const considered = copies.filter(note => !isGeneratedIndex(note.text));
  const repairs = [];
  const needs = [];

  for (const note of copies) {
    if (isGeneratedIndex(note.text)) continue;
    for (const link of linksIn(note)) {
      let broken = false;
      if (link.kind === 'md') broken = brokenMarkdown(link, paths);
      else broken = wikiHits(link.wikiName, copies).length === 0;
      if (!broken) continue;

      const candidates = candidateNotes(link.fileName, copies);
      if (link.unreadable) {
        needs.push(needsYou(note, link, [], UNREADABLE));
        continue;
      }
      if (candidates.length === 0) {
        needs.push(needsYou(note, link, [], NO_MATCH));
        continue;
      }
      if (candidates.length > 1) {
        needs.push(needsYou(note, link, candidates, MANY));
        continue;
      }
      const dest = candidates[0];
      if (dest.path === note.path) {
        needs.push(needsYou(note, link, candidates, SELF));
        continue;
      }
      if (!saved) {
        needs.push(needsYou(note, link, candidates, NO_SNAPSHOT));
        continue;
      }
      const oldPath = oldSnapshotPath(link, saved);
      const old = oldPath ? snapshotNote(saved, oldPath) : undefined;
      const gone = oldPath && !storedPath(paths, oldPath);
      const arrived = !snapshotNote(saved, dest.path);
      const sameBytes = old && sha256Text(dest.text) === old.sha256;
      if (!old || !gone || !arrived || !sameBytes) {
        needs.push(needsYou(note, link, candidates, NOT_A_MOVE));
        continue;
      }
      let to = '';
      if (link.kind === 'md') {
        to = `${encodePath(relativePath(parentDir(note.path), dest.path))}${link.suffix}`;
      } else {
        to = wikiReplacement(note, link, dest, copies);
        if (!to) {
          needs.push(needsYou(note, link, candidates, UNSAFE_WIKI));
          continue;
        }
      }
      if (to === link.from) {
        needs.push(needsYou(note, link, candidates, ALREADY));
        continue;
      }
      repairs.push(hidden({
        path: note.path,
        line: link.line,
        from: link.from,
        to,
      }, {
        column: link.column,
        detail: link.detail,
        dest: dest.path,
        destHash: sha256Text(dest.text),
        start: link.start,
        end: link.end,
      }));
    }
  }

  repairs.sort((a, b) => compareText(a.path, b.path) || a.line - b.line || a.column - b.column);
  needs.sort((a, b) => compareText(a.path, b.path) || a.line - b.line || a.column - b.column);

  const byPath = new Map(copies.map(note => [note.path, note]));
  const grouped = new Map();
  for (const repair of repairs) {
    if (!grouped.has(repair.path)) grouped.set(repair.path, []);
    grouped.get(repair.path).push(repair);
  }
  const writes = [];
  for (const [notePath, items] of grouped) {
    writes.push({ path: notePath, text: applyRepairs(byPath.get(notePath).text, items) });
  }
  writes.sort((a, b) => compareText(a.path, b.path));

  return {
    repairs,
    needsYou: needs,
    writes,
    counts: {
      notes: considered.length,
      broken: repairs.length + needs.length,
      repairs: repairs.length,
      needsYou: needs.length,
    },
  };
}

/** Apply repair spans to one note. Later spans are applied first so offsets stay put. */
export function applyRepairs(text, repairs) {
  const ordered = repairs.slice().sort((a, b) => b.start - a.start || b.end - a.end);
  let out = text;
  for (const repair of ordered) {
    out = `${out.slice(0, repair.start)}${repair.to}${out.slice(repair.end)}`;
  }
  return out;
}

/** The lines a dry run prints. */
export function formatReport(result, options = {}) {
  const lines = [];
  if (options.noSnapshot && result.counts.broken > 0) {
    lines.push('No snapshot yet. Run --record, then later moves can be repaired.');
  }
  for (const repair of result.repairs) {
    lines.push(`${repair.path}:${repair.line} ${repair.from} → ${repair.to}`);
  }
  for (const item of result.needsYou) {
    const where = item.candidates.length ? item.candidates.join(', ') : 'no candidates';
    lines.push(`${item.path}:${item.line} ${item.link} needs you (${item.reason}): ${where}`);
  }
  if (!result.repairs.length && !result.needsYou.length) lines.push('No broken links to repair.');
  return `${lines.join('\n')}\n`;
}
